import { useState } from "react";

export default function MappingContractViewer({
  mapping,
  onEditRule,
  onRemoveRule,
  approved,
  allHeaders = [],
  mappedSources = new Set(),
  unmappedHeaders = [],
  onMapAllRemaining,
  onMapSingleExtension,
}) {
  const [viewMode, setViewMode] = useState("table"); // "table" | "json" | "flow"
  const [copied, setCopied] = useState(false);

  if (!mapping) return null;

  const copyJson = () => {
    navigator.clipboard.writeText(JSON.stringify(mapping, null, 2));
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const downloadJson = () => {
    const blob = new Blob([JSON.stringify(mapping, null, 2)], {
      type: "application/json",
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${mapping.name || "mapping"}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="card" style={{ padding: "18px 20px" }}>
      {/* Header with Mode Toggles */}
      <div className="row between" style={{ marginTop: 0, marginBottom: "14px", alignItems: "center" }}>
        <div>
          <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
            <h3 style={{ margin: 0, fontSize: "15px" }}>
              2. Mapping Contract: <code>{mapping.name}</code>
            </h3>
            <span className={`chip ${approved ? "ok" : "warn"}`} style={{ fontSize: "11px" }}>
              {approved ? "✓ Approved Contract" : "Pending Review"}
            </span>
          </div>
          <p className="sub-meta" style={{ margin: "3px 0 0" }}>
            Deterministic FHIR R4 schema transformation contract generated by Google Gemini.
          </p>
        </div>

        {/* View Switcher Pills */}
        <div style={{ display: "flex", gap: "6px", alignItems: "center" }}>
          <button
            className={`secondary sm ${viewMode === "table" ? "active-pill" : ""}`}
            style={{
              fontSize: "12px",
              padding: "5px 12px",
              background: viewMode === "table" ? "rgba(59, 130, 246, 0.25)" : "rgba(255, 255, 255, 0.05)",
              borderColor: viewMode === "table" ? "rgba(59, 130, 246, 0.6)" : "var(--card-border)",
            }}
            onClick={() => setViewMode("table")}
          >
            📋 Interactive Table
          </button>
          <button
            className={`secondary sm ${viewMode === "flow" ? "active-pill" : ""}`}
            style={{
              fontSize: "12px",
              padding: "5px 12px",
              background: viewMode === "flow" ? "rgba(59, 130, 246, 0.25)" : "rgba(255, 255, 255, 0.05)",
              borderColor: viewMode === "flow" ? "rgba(59, 130, 246, 0.6)" : "var(--card-border)",
            }}
            onClick={() => setViewMode("flow")}
          >
            🔀 Lineage &amp; Flow
          </button>
          <button
            className={`secondary sm ${viewMode === "json" ? "active-pill" : ""}`}
            style={{
              fontSize: "12px",
              padding: "5px 12px",
              background: viewMode === "json" ? "rgba(59, 130, 246, 0.25)" : "rgba(255, 255, 255, 0.05)",
              borderColor: viewMode === "json" ? "rgba(59, 130, 246, 0.6)" : "var(--card-border)",
            }}
            onClick={() => setViewMode("json")}
          >
            &#123; &#125; Raw JSON Spec
          </button>
        </div>
      </div>

      {/* Field Coverage Analysis Bar */}
      <div
        style={{
          background: "rgba(0,0,0,0.25)",
          padding: "10px 14px",
          borderRadius: "var(--radius-md)",
          marginBottom: "14px",
          border: "1px solid var(--card-border)",
        }}
      >
        <div className="row between" style={{ margin: 0, alignItems: "center" }}>
          <div style={{ fontSize: "12px" }}>
            <strong>Field Coverage: </strong>
            <span style={{ color: "var(--ok)", fontWeight: 700 }}>
              {mappedSources.size} Mapped
            </span>
            {" • "}
            <span
              style={{
                color: unmappedHeaders.length > 0 ? "var(--warn)" : "var(--ok)",
                fontWeight: 700,
              }}
            >
              {unmappedHeaders.length} Unmapped / Skipped
            </span>
            {" / "}
            <span>{allHeaders.length} Total Columns</span>
          </div>

          <div style={{ display: "flex", gap: "8px", alignItems: "center" }}>
            <span className={`chip ${unmappedHeaders.length === 0 ? "ok" : "warn"}`} style={{ fontSize: "11px" }}>
              {Math.round((mappedSources.size / Math.max(1, allHeaders.length)) * 100)}% Coverage
            </span>
            {unmappedHeaders.length > 0 && (
              <button
                className="secondary sm"
                style={{ fontSize: "11px", padding: "2px 8px" }}
                onClick={onMapAllRemaining}
                title="Automatically map all remaining unmapped columns as FHIR R4 Extensions"
              >
                ✨ Map All Remaining as Extensions
              </button>
            )}
          </div>
        </div>

        {unmappedHeaders.length > 0 && (
          <div style={{ marginTop: "6px", fontSize: "11px" }}>
            <span style={{ color: "var(--text-muted)" }}>
              Unmapped Columns (Click to map as extension):{" "}
            </span>
            {unmappedHeaders.map((col) => (
              <span
                key={col}
                className="rule-tag"
                style={{
                  cursor: "pointer",
                  background: "rgba(245, 158, 11, 0.1)",
                  color: "var(--warn)",
                  borderColor: "rgba(245, 158, 11, 0.3)",
                  marginRight: "4px",
                  display: "inline-block",
                  padding: "1px 6px",
                  borderRadius: "4px",
                }}
                onClick={() => onMapSingleExtension(col)}
                title={`Click to map "${col}" as a FHIR Extension`}
              >
                + {col}
              </span>
            ))}
          </div>
        )}
      </div>

      {/* VIEW 1: INTERACTIVE TABLE */}
      {viewMode === "table" && (
        <table>
          <thead>
            <tr>
              <th style={{ width: "22%" }}>Source Column</th>
              <th style={{ width: "30%" }}>Target FHIR Path</th>
              <th style={{ width: "20%" }}>Transform</th>
              <th style={{ width: "12%" }}>Confidence</th>
              <th style={{ width: "10%", textAlign: "right" }} />
            </tr>
          </thead>
          <tbody>
            {mapping.rules?.map((r, i) => (
              <tr key={i} title={r.rationale || ""}>
                <td>
                  <input
                    value={r.source}
                    onChange={(e) => onEditRule(i, "source", e.target.value)}
                    style={{ padding: "4px 8px", fontSize: "12px", width: "100%" }}
                  />
                </td>
                <td>
                  <input
                    value={r.target}
                    onChange={(e) => onEditRule(i, "target", e.target.value)}
                    style={{
                      padding: "4px 8px",
                      fontSize: "12px",
                      width: "100%",
                      fontFamily: "monospace",
                    }}
                  />
                </td>
                <td>
                  <select
                    value={r.transform || "direct"}
                    onChange={(e) => onEditRule(i, "transform", e.target.value)}
                    style={{ padding: "4px 8px", fontSize: "12px", width: "100%" }}
                  >
                    <option value="direct">direct</option>
                    <option value="date">date</option>
                    <option value="map">map</option>
                    <option value="upper">upper</option>
                    <option value="lower">lower</option>
                    <option value="strip">strip</option>
                  </select>
                </td>
                <td>
                  <span
                    className="chip"
                    style={{
                      background: (r.confidence || 1) >= 0.9 ? "rgba(16, 185, 129, 0.15)" : "rgba(245, 158, 11, 0.15)",
                      color: (r.confidence || 1) >= 0.9 ? "var(--ok)" : "var(--warn)",
                      fontSize: "11px",
                    }}
                  >
                    {Math.round((r.confidence || 1) * 100)}%
                  </span>
                  {(r.notes?.includes("Self-healed") || r.notes?.includes("healed")) && (
                    <span
                      className="chip"
                      style={{
                        background: "rgba(168, 85, 247, 0.2)",
                        color: "#c084fc",
                        border: "1px solid rgba(168, 85, 247, 0.4)",
                        fontSize: "10px",
                        marginLeft: "4px",
                      }}
                      title={r.notes}
                    >
                      🩹 Healed
                    </span>
                  )}
                </td>
                <td style={{ textAlign: "right" }}>
                  <button
                    className="secondary sm"
                    onClick={() => onRemoveRule(i)}
                    style={{
                      color: "var(--bad)",
                      borderColor: "rgba(239, 68, 68, 0.3)",
                      padding: "2px 8px",
                    }}
                    title="Remove rule"
                  >
                    ✕
                  </button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      )}

      {/* VIEW 2: LINEAGE & FLOW DIAGRAM */}
      {viewMode === "flow" && (
        <div
          style={{
            display: "grid",
            gridTemplateColumns: "repeat(auto-fill, minmax(320px, 1fr))",
            gap: "10px",
            maxHeight: "420px",
            overflowY: "auto",
            padding: "8px",
            background: "rgba(0,0,0,0.2)",
            borderRadius: "var(--radius-md)",
          }}
        >
          {mapping.rules?.map((r, i) => (
            <div
              key={i}
              style={{
                background: "rgba(255, 255, 255, 0.03)",
                border: "1px solid var(--card-border)",
                borderRadius: "var(--radius-md)",
                padding: "8px 12px",
                display: "flex",
                alignItems: "center",
                justifyContent: "space-between",
                gap: "8px",
              }}
            >
              <div style={{ fontWeight: 600, fontSize: "12px", color: "var(--accent)" }}>
                {r.source}
              </div>

              <div style={{ display: "flex", alignItems: "center", gap: "6px" }}>
                <span
                  style={{
                    fontSize: "10px",
                    padding: "1px 6px",
                    borderRadius: "4px",
                    background: "rgba(59, 130, 246, 0.2)",
                    color: "#93c5fd",
                  }}
                >
                  {r.transform || "direct"}
                </span>
                <span style={{ color: "var(--text-muted)", fontSize: "12px" }}>──►</span>
              </div>

              <div
                style={{
                  fontFamily: "monospace",
                  fontSize: "11px",
                  color: "#34d399",
                  maxWidth: "140px",
                  overflow: "hidden",
                  textOverflow: "ellipsis",
                  whiteSpace: "nowrap",
                }}
                title={r.target}
              >
                {r.target}
              </div>
            </div>
          ))}
        </div>
      )}

      {/* VIEW 3: RAW JSON CONTRACT SPECIFICATION */}
      {viewMode === "json" && (
        <div>
          <div className="row between" style={{ margin: "0 0 8px" }}>
            <span style={{ fontSize: "12px", color: "var(--text-muted)" }}>
              Official declarative contract: <code>mappings/{mapping.name.toLowerCase()}.json</code>
            </span>
            <div style={{ display: "flex", gap: "8px" }}>
              <button className="secondary sm" onClick={copyJson}>
                {copied ? "✓ Copied!" : "📋 Copy Contract JSON"}
              </button>
              <button className="secondary sm" onClick={downloadJson}>
                💾 Download .json
              </button>
            </div>
          </div>

          <pre
            style={{
              background: "#090d16",
              border: "1px solid var(--card-border)",
              borderRadius: "var(--radius-md)",
              padding: "14px 16px",
              fontSize: "12px",
              color: "#a5b4fc",
              maxHeight: "420px",
              overflowY: "auto",
              fontFamily: "Consolas, Menlo, Monaco, monospace",
              lineHeight: "1.4",
            }}
          >
            {JSON.stringify(mapping, null, 2)}
          </pre>
        </div>
      )}
    </div>
  );
}

